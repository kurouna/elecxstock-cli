// E2E: 実際の読み口と画面にキーを流し、画面の文字で確かめる（データは種の写し。値はすべて架空）
import { afterEach, describe, expect, it } from 'vitest'
import { K, type Started, start } from '../support/app'

let app: Started | undefined
afterEach(() => {
  app?.stop()
  app = undefined
})
const sel = () => app!.selected() ?? ''

describe('起動と画面の切り替え', () => {
  it('起動するとウォッチリスト（お気に入り）。状態の行にデータの基準・アラートの数・次の予定、タブは 5 つ', async () => {
    app = await start()
    const f = app.frame()
    expect(f).toContain('elecxstock-cli')
    expect(f).toContain('データ 11/13')
    expect(f).toContain('アラート 1')
    for (const t of ['1 マーケット', '2 スクリーナー', '3 ウォッチリスト', '4 保有', '5 ポートフォリオ']) expect(f).toContain(t)
    expect(f).toContain('お気に入り 8 銘柄')
    expect(sel()).toContain('8951')
  })
  it('1〜5 で画面を切り替え、Tab・Shift+Tab で巡る。全角の数字でも切り替わる', async () => {
    app = await start()
    await app.press('1')
    await app.until('騰落')
    expect(app.frame()).toContain('値上がり率')
    await app.press('2')
    await app.until('条件')
    await app.press('4')
    await app.until('合計')
    await app.press('5')
    await app.until('資産推移')
    expect(app.frame()).toContain('評価額（現金を除く）')
    await app.press(K.tab)
    await app.until('騰落') // 5 の次は 1
    await app.press(K.shiftTab)
    await app.until('資産推移')
    await app.press('３')
    await app.until('お気に入り 8 銘柄')
  })
})

describe('一覧の選択', () => {
  it('↓↑ で行を選び、端では止まる。PgDn は 10 行先（最後で止まる）。位置を「n / 件数」で出す', async () => {
    app = await start()
    expect(app.frame()).toContain('1 / 8')
    await app.press(K.down)
    expect(sel()).toContain('8058')
    expect(app.frame()).toContain('2 / 8')
    await app.press(K.up, K.up)
    expect(sel()).toContain('8951')
    await app.press(K.pageDown)
    expect(sel()).toContain('8766')
    expect(app.frame()).toContain('8 / 8')
    await app.press(K.down)
    expect(sel()).toContain('8766')
    await app.press(K.pageUp)
    expect(sel()).toContain('8951')
  })
  it('[ ] でリストを切り替えると、選択は先頭に戻る', async () => {
    app = await start()
    await app.press(K.down)
    await app.press(']')
    await app.until('売買候補 3 銘柄')
    expect(sel()).toContain('4063')
    await app.press('[')
    await app.until('お気に入り 8 銘柄')
    expect(sel()).toContain('8951')
  })
  it('s で並べ替えると、選んだ銘柄のまま（位置ではなく銘柄で覚える）', async () => {
    app = await start()
    await app.press(K.down) // 8058
    await app.press('s')
    await app.until((f) => !f.includes('登録順'))
    expect(sel()).toContain('8058')
  })
})

describe('詳細（Enter で入る）', () => {
  it('Enter で選んだ銘柄の詳細。Backspace で戻ると、元の画面の同じ行が選ばれている。Esc でも戻る', async () => {
    app = await start()
    await app.press(K.down, K.enter)
    await app.until('› 8058 三菱商事')
    expect(app.frame()).toContain('指標')
    await app.press(K.backspace)
    await app.until('お気に入り 8 銘柄')
    expect(sel()).toContain('8058')
    await app.press(K.enter)
    await app.until('› 8058')
    await app.press(K.esc)
    await app.until((f) => !f.includes('› 8058'))
  })
  it('n N で元の一覧の次・前の銘柄', async () => {
    app = await start()
    await app.press(K.down, K.enter)
    await app.until('› 8058')
    await app.press('n')
    await app.until('› 7203')
    await app.press('N', 'N')
    await app.until('› 8951')
  })
  it(', . で期間、t で時間軸を切り替える', async () => {
    app = await start()
    await app.press(K.enter)
    await app.until('1Y の騰落')
    expect(app.frame()).toContain('日足')
    await app.press('.')
    await app.until('5Y の騰落')
    await app.press(',', ',')
    await app.until('6M の騰落')
    await app.press('t')
    await app.until('週足')
    await app.press('t')
    await app.until('月足')
    await app.press('t')
    await app.until('日足')
  })
  it('詳細には目標利回り（設定の 4%・5.5%）と、保有・アラートを出す', async () => {
    app = await start()
    await app.press(K.down, K.down, K.down, K.enter) // 8306（保有あり・アラートあり）
    await app.until('› 8306')
    const f = app.frame()
    expect(f).toContain('目標利回り')
    expect(f).toMatch(/4%/)
    expect(f).toContain('NISA成長')
    expect(f).toContain('アラート')
  })
  it('詳細から数字のキーで別の画面へ移れる（詳細は閉じる）', async () => {
    app = await start()
    await app.press(K.enter)
    await app.until('› 8951')
    await app.press('4')
    await app.until('合計')
    expect(app.frame()).not.toContain('› 8951')
  })
})

describe('コードを打って開く（/）', () => {
  it('/ のあと数字は入力に回り（画面は切り替わらない）、Enter で開く', async () => {
    app = await start()
    await app.press('/', '8', '9', '5', '1')
    await app.until('コード: 8951')
    expect(app.frame()).toContain('お気に入り 8 銘柄')
    await app.press(K.enter)
    await app.until('› 8951 日本ビルファンド投資法人')
  })
  it('Backspace で 1 字消し、Esc でやめる。無いコードは知らせる', async () => {
    app = await start()
    await app.press('/', '1', '2', K.backspace)
    await app.until(/コード: 1(?!2)/)
    await app.press(K.esc)
    await app.until((f) => !f.includes('コード:'))
    await app.press('/', '0', '0', '0', '0', K.enter)
    await app.until('0000 の銘柄はありません')
    expect(app.frame()).not.toContain('›')
  })
})

describe('格子（v）', () => {
  it('v で格子にし、← → で選び、Enter で詳細。, . で期間。v で表に戻る', async () => {
    app = await start()
    await app.press('v')
    await app.until('〜')
    expect(app.frame()).not.toContain('52週の位置')
    await app.press(K.right)
    await app.press(K.enter)
    await app.until('› 8058')
    await app.press(K.backspace)
    await app.until('〜')
    await app.press('.')
    await app.until('5Y +')
    await app.press('v')
    await app.until('52週の位置')
  })
})

describe('スクリーナー・保有・ポートフォリオ', () => {
  it('2 のスクリーナーは保存したスクリーンを [ ] で切り替え、結果の件数を出す', async () => {
    app = await start({ tab: 2 })
    await app.until('条件')
    const first = app.frame()
    expect(first).toMatch(/結果 \d+ 件/)
    await app.press(']')
    await app.until((f) => f !== first && /結果 \d+ 件/.test(f))
  })
  it('4 の保有は口座ごとの小計と合計。m で金額を隠し、もう一度 m で出す', async () => {
    app = await start({ tab: 4 })
    await app.until('合計')
    const f = app.frame()
    for (const a of ['NISA成長', 'つみたて', '特定']) expect(f).toContain(a)
    await app.press('m')
    await app.until('金額を隠しています')
    expect(app.frame()).toContain('••••••')
    await app.press('m')
    await app.until((x) => !x.includes('金額を隠しています'))
  })
  it('5 のポートフォリオは今後 30 日の予定と損益寄与。c で寄与の期間を巡る', async () => {
    app = await start({ tab: 5 })
    await app.until('損益寄与（今日）')
    expect(app.frame()).toContain('今後 30 日の予定')
    await app.press('c')
    await app.until('損益寄与（今月）')
    await app.press('c')
    await app.until('損益寄与（今年）')
  })
  it('1 のマーケットは日付の列と騰落、値上がり率から Enter で詳細', async () => {
    app = await start({ tab: 1 })
    await app.until('騰落')
    expect(app.frame()).toContain('日経平均')
    expect(app.frame()).toContain('日付')
    await app.press(K.enter)
    await app.until('›')
  })
})

describe('キーの一覧・終了', () => {
  it('? でキーの一覧、何かキーで閉じる', async () => {
    app = await start()
    await app.press('?')
    await app.until('何かキーを押すと閉じる')
    await app.press('x')
    await app.until('お気に入り 8 銘柄')
  })
  it('q で終わる', async () => {
    app = await start()
    await app.press('q')
    expect(app.exited()).toBe(true)
  })
})
